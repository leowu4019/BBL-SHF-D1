print("Starting LEI Update....")

import pandas as pd
from fredapi import Fred
import os

try:
    from google.colab import auth
    from google.colab import userdata
    api_key = userdata.get('API_KEY')
except:
    api_key = os.environ.get('API_KEY')

fred = Fred(api_key=api_key)

fred_map = {
    'mfg_hours': 'AWHMAN',
    'claims': 'ICSA',
    'consumer_orders': 'ACOGNO',
    'capital_goods': 'NEWORDER',
    'permits': 'PERMIT',
    'sp500': 'SP500',
    'credit_idx': 'NFCI',
    'ir_spread': 'T10YFF'
}

def fetch_fred(series_id, name):
    df = fred.get_series(series_id).resample('MS').mean().to_frame(name)
    df.index.name = 'date'
    df = df.reset_index()
    df['yyyy_mm'] = df['date'].dt.strftime('%Y-%m')

    return df[['yyyy_mm', name]]

fred_dfs = [fetch_fred(sid, name) for name, sid in fred_map.items()]
combined_df = fred_dfs[0]
for next_df in fred_dfs[1:]:
    combined_df = pd.merge(combined_df, next_df, on='yyyy_mm', how='inner')

filename = 'manual_variables.csv'
manual_df = pd.read_csv(filename)

final_df = pd.merge(combined_df, manual_df, on='yyyy_mm', how='inner')

final_df = final_df[final_df['yyyy_mm'] >= '2025-09'].sort_values('yyyy_mm')

final_df.to_csv('lei_2026.csv', index=False)
print("Dataset succesfully aligned to start in September 2025")

